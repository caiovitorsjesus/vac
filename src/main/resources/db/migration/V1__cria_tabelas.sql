-- Esquema inicial: disciplinas, faltas e avaliações.
-- Tipos e restrições espelham as entidades JPA; o Hibernate valida essa correspondência ao subir.

CREATE TABLE disciplina (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                     VARCHAR(100)  NOT NULL,
    carga_horaria_total      NUMERIC(6, 2) NOT NULL,
    percentual_maximo_faltas NUMERIC(6, 2) NOT NULL,
    media_minima             NUMERIC(6, 2) NOT NULL,
    nota_maxima              NUMERIC(6, 2) NOT NULL
);

CREATE TABLE registro_falta (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT        NOT NULL REFERENCES disciplina (id),
    data          DATE          NOT NULL,
    horas         NUMERIC(6, 2) NOT NULL,
    observacao    VARCHAR(255)
);

CREATE TABLE avaliacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id   BIGINT        NOT NULL REFERENCES disciplina (id),
    nome            VARCHAR(100)  NOT NULL,
    peso_percentual NUMERIC(6, 2) NOT NULL,
    nota            NUMERIC(6, 2)
);

-- o PostgreSQL não indexa chaves estrangeiras sozinho; toda listagem filtra por disciplina_id
CREATE INDEX idx_registro_falta_disciplina ON registro_falta (disciplina_id);
CREATE INDEX idx_avaliacao_disciplina ON avaliacao (disciplina_id);
